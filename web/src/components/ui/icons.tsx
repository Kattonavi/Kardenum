import type { ReactNode } from "react";

// One icon system, drawn as in the mockups: 24 px grid, 2 px stroke, square caps. All decorative.
type IconProps = { size?: number; className?: string };

function Icon({ size = 16, className, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="square"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {children}
    </svg>
  );
}

